#!/usr/bin/env python3
"""Write tools/art/provenance.toml: one row per generated PNG under godot/assets
(path, kind, source, generator, licence). Rerun after every build."""
import os

from pal import ROOT

ASSETS = os.path.join(ROOT, 'godot', 'assets')
OUT = os.path.join(ROOT, 'tools', 'art', 'provenance.toml')
GENERATOR = {
    'audio': 'tools/art/sound.py',
    'palette': 'tools/art/palette.py', 'terrain': 'tools/art/terrain.py',
    'overlays': 'tools/art/overlays.py', 'structures': 'tools/art/structures.py',
    'plants': 'tools/art/plants.py', 'items': 'tools/art/items.py', 'light': 'tools/art/light.py',
    'people': 'tools/art/people.py', 'animals': 'tools/art/animals.py',
    'items32': 'tools/art/items_derived.py',
    'effects': 'tools/art/effects.py',
}
# Some overlays are generated by a focused art slice rather than the historical all-overlays
# generator. Keep the provenance row precise without relabelling the existing overlay family.
GENERATOR_BY_PATH = {
    # FIXLOG 2026-11-19: these eight are text-template 2x defaults, not sheet crops.
    **{'godot/assets/items32/' + name + '.png': 'tools/art/items.py'
       for name in ('bed_frame', 'chest', 'door', 'dye', 'rough_stone', 'stool', 'table', 'thatch')},
    'godot/assets/overlays/cave_seepage.png': 'tools/art/underground.py',
    'godot/assets/overlays/strata_face.png': 'tools/art/underground.py',
}
# Assets derived from generated reference sheets (items_derived.py writes this): their rows
# carry the sheet, model, service and licence instead of "generated, project-original".
DERIVED = os.path.join(ROOT, 'tools', 'art', 'sources', 'derived_assets.json')


def main():
    # FIXLOG 2026-11-19: policy precedes old sheet metadata and folder fallbacks.
    import replacement_policy
    protected = replacement_policy.audit()
    rows = []
    for root, _, names in os.walk(ASSETS):
        for n in sorted(names):
            if not (n.endswith('.png') or n.endswith('.wav')):
                continue
            rel = os.path.relpath(os.path.join(root, n), ROOT)
            # Forward slashes always: on Windows relpath emits backslashes, and a backslash inside
            # a quoted TOML string is an invalid escape, so the table would not parse at all.
            rel = rel.replace('\\', '/')
            kind = os.path.relpath(root, ASSETS).split(os.sep)[0]
            rows.append((rel, kind, GENERATOR_BY_PATH.get(rel, GENERATOR.get(kind, 'tools/art/' + kind + '.py'))))
    rows.sort()
    import json
    derived = json.load(open(DERIVED)) if os.path.exists(DERIVED) else {}
    with replacement_policy.atomic_text(OUT) as f:
        f.write('# Generated by tools/art/provenance.py; every art file under godot/assets.\n\n')
        for rel, kind, gen in rows:
            if rel in protected:
                f.write("[[asset]]\n" + "".join(k + " = " + json.dumps(v) + "\n" for k, v in replacement_policy.provenance(protected[rel]).items()) + "\n")
                continue
            d = derived.get(rel)
            if d:
                f.write('[[asset]]\npath = "%s"\nkind = "%s"\nsource = "derived"\ngenerator = "%s"\n'
                        'licence = %s\nsheet = "%s"\nsheet_sha256 = "%s"\nmodel = "%s"\nservice = "%s"\n'
                        'prompt_file = "%s"\ncrop = %s\n\n'
                        % (rel, kind, d['generator'], json.dumps(d['licence']), d['sheet'],
                           d['sheet_sha256'], d['model'], d['service'], d['prompt_file'],
                           json.dumps(d['crop'])))
                continue
            f.write('[[asset]]\npath = "%s"\nkind = "%s"\nsource = "generated"\ngenerator = "%s"\nlicence = "project-original"\n\n'
                    % (rel, kind, gen))
    print('provenance: %d rows -> %s' % (len(rows), OUT))


PEOPLE_TABLE = os.path.join(ROOT, 'tools', 'art', 'provenance_people.toml')


def _blocks(path):
    """(header, [(asset path, block text)]) of a provenance table, block text without the marker."""
    with open(path) as f:
        text = f.read()
    parts = text.split('[[asset]]\n')
    rows = []
    for b in parts[1:]:
        first = b.split('\n', 1)[0]
        rows.append((first.split('"')[1] if '"' in first else '', b))
    return parts[0], rows


def _write(path, header, rows):
    with open(path, 'w') as f:
        f.write(header + ''.join('[[asset]]\n' + b for _, b in rows))


def refresh_folder(kind, describe):
    """Rewrite the rows for every file in godot/assets/<kind> in both art tables, after a
    generator run: provenance.toml gets the plain row, provenance_people.toml the detailed row
    (size, sha256 prefix, description from describe(filename)). Rows for other folders are left
    exactly as they are, so one generator's run touches only its own rows."""
    import hashlib
    from PIL import Image
    # Refuse whole protected folder refresh before either table is written.
    import replacement_policy
    protected = replacement_policy.audit()
    if any(p.startswith('godot/assets/' + kind + '/') for p in protected):
        raise ValueError('protected provenance folder refresh')
    folder = os.path.join(ASSETS, kind)
    names = sorted(n for n in os.listdir(folder) if n.endswith('.png') or n.endswith('.json'))
    prefix = 'godot/assets/%s/' % kind
    gen = GENERATOR[kind]
    header, rows = _blocks(OUT)
    at = next((i for i, r in enumerate(rows) if r[0].startswith(prefix)), len(rows))
    rest = [r for r in rows if not r[0].startswith(prefix)]
    plain = [(prefix + n, 'path = "%s"\nkind = "%s"\nsource = "generated"\ngenerator = "%s"\n'
              'licence = "project-original"\n\n' % (prefix + n, kind, gen))
             for n in names if n.endswith('.png')]
    _write(OUT, header, rest[:at] + plain + rest[at:])
    header, rows = _blocks(PEOPLE_TABLE)
    at = next((i for i, r in enumerate(rows) if r[0].startswith(prefix)), len(rows))
    rest = [r for r in rows if not r[0].startswith(prefix)]
    at = min(at, len(rest))
    fresh = []
    for n in names:
        full = os.path.join(folder, n)
        with open(full, 'rb') as f:
            sha = hashlib.sha256(f.read()).hexdigest()[:16]
        size = '%dx%d' % Image.open(full).size if n.endswith('.png') else ''
        fresh.append((prefix + n, 'path = "%s"\ngenerator = "%s"\ncommand = "python3 %s"\nsource = "procedural"\n'
                      'licence = "project"\nsize = "%s"\nsha256_16 = "%s"\ndescription = "%s"\n\n'
                      % (prefix + n, gen, gen, size, sha, describe(n))))
    _write(PEOPLE_TABLE, header, rest[:at] + fresh + rest[at:])
    print('provenance: %d rows for %s' % (len(fresh), prefix))


if __name__ == '__main__':
    main()
