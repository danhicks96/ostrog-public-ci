def sprite(name,size):
 base=base_for(name);im=Image.new('RGBA',(16,16))
 if base in T:
  tpl=T[base];assert len(tpl)==16 and all(len(row)==16 for row in tpl)
  for y,row in enumerate(tpl):
   for x,ch in enumerate(row):
    if ch!='.': im.putpixel((x,y),M[ch])
  origin='tracked-text-template:'+base
 else:im=geom(base);origin='new-geometric:'+base
 suffix=name[len(base):].lstrip('_')
 if suffix:
  ramp=('gold' if suffix in ('gold','bronze','gold_ore') else 'copper' if suffix=='copper' else 'stone' if any(s in suffix for s in ('stone','slate','basalt','granite','marble','silver','tin','gabbro','gneiss')) else 'foliage' if suffix=='emerald' else 'water' if suffix=='sapphire' else 'warm' if suffix=='garnet' else 'cool' if suffix=='amethyst' else 'earth')
  shift=int(hashlib.sha256(suffix.encode()).hexdigest()[:2],16)%3-1
  for y in range(16):
   for x in range(16):
    p=im.getpixel((x,y))
    if p[3] and p!=COL['black']:
     step=max(1,min(7,round(sum(p[:3])/3/255*7)+shift));im.putpixel((x,y),c(ramp,step))
 if size==32: im=im.resize((32,32),Image.Resampling.NEAREST)
 return im,origin,suffix

